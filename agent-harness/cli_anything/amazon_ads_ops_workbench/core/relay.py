"""Hub side of the relay: sends Amazon HTTP calls through an ads-relay server.

The handler plugs into urllib, so callers keep their usual error handling:
non-2xx upstream answers still surface as HTTPError, relay faults as URLError.
"""

from __future__ import annotations

import hashlib
import http.client
import json
import secrets
import ssl
import time
from dataclasses import dataclass, field
from urllib import error, request
from urllib.response import addinfourl

from .relay_agent import DROP_HEADERS, allowed_url, decode_meta, encode_meta, sign


@dataclass(frozen=True)
class RelayEndpoint:
    id: str
    name: str
    host: str
    port: int
    fingerprint: str
    secret: str = field(repr=False)


def pinned_connection(relay: RelayEndpoint, timeout: float) -> http.client.HTTPSConnection:
    # Self-signed certificate generated by the hub; trust is the pinned SHA-256.
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.check_hostname = False
    context.verify_mode = ssl.CERT_NONE
    conn = http.client.HTTPSConnection(relay.host, relay.port, timeout=timeout, context=context)
    try:
        conn.connect()
        der = conn.sock.getpeercert(binary_form=True) or b""
    except (OSError, ssl.SSLError) as exc:
        conn.close()
        raise error.URLError(f"转发服务器 {relay.name} 无法连接: {exc}") from None
    if hashlib.sha256(der).hexdigest() != relay.fingerprint:
        conn.close()
        raise error.URLError(f"转发服务器 {relay.name} 证书指纹不匹配，已拒绝连接")
    return conn


def signed_headers(relay: RelayEndpoint, meta: str, body: bytes) -> dict[str, str]:
    stamp, nonce = str(int(time.time())), secrets.token_hex(16)
    return {
        "X-Relay-Time": stamp,
        "X-Relay-Nonce": nonce,
        "X-Relay-Meta": meta,
        "X-Relay-Signature": sign(relay.secret, stamp, nonce, meta, body),
    }


def relay_error(relay: RelayEndpoint, resp: http.client.HTTPResponse) -> error.URLError:
    try:
        message = json.loads(resp.read(4096)).get("relay_error", "")
    except Exception:
        message = ""
    resp.close()
    return error.URLError(f"转发服务器 {relay.name} 拒绝请求 ({resp.status} {message})".strip())


class RelayHandler(request.HTTPSHandler):
    handler_order = 100

    def __init__(self, relay: RelayEndpoint):
        super().__init__()
        self.relay = relay

    def http_open(self, req):
        raise error.URLError("转发模式只允许 HTTPS 请求")

    def https_open(self, req):
        url = req.full_url
        if not allowed_url(url):
            raise error.URLError("转发模式只允许访问 Amazon Ads / S3 地址")
        body = req.data or b""
        if not isinstance(body, bytes):
            raise error.URLError("转发模式只支持 bytes 请求体")
        timeout = req.timeout if isinstance(req.timeout, (int, float)) else 60
        meta = encode_meta(
            {
                "m": req.get_method(),
                "u": url,
                "h": [[k, v] for k, v in req.header_items() if k.lower() not in DROP_HEADERS],
                "t": timeout,
            }
        )
        conn = pinned_connection(self.relay, timeout + 15)
        try:
            conn.request(
                "POST",
                "/v1/forward",
                body=body,
                headers={**signed_headers(self.relay, meta, body), "Content-Type": "application/octet-stream"},
            )
            resp = conn.getresponse()
        except (OSError, http.client.HTTPException) as exc:
            conn.close()
            raise error.URLError(f"转发服务器 {self.relay.name} 通信失败: {exc}") from None
        if resp.getheader("X-Relay-Error") or not resp.getheader("X-Relay-Status"):
            raise relay_error(self.relay, resp)
        headers = http.client.HTTPMessage()
        for key, value in decode_meta(resp.getheader("X-Relay-Headers", "W10=")):
            headers[key] = value
        # Stream the upstream body: callers read reports with their own size cap.
        result = addinfourl(resp, headers, url, int(resp.getheader("X-Relay-Status")))
        result.msg = resp.getheader("X-Relay-Reason", "")
        return result


def opener_for(relay: RelayEndpoint | None, *handlers) -> request.OpenerDirector:
    if relay is None:
        return request.build_opener(*handlers)
    return request.build_opener(*handlers, RelayHandler(relay))


def health(relay: RelayEndpoint, timeout: float = 10) -> dict:
    conn = pinned_connection(relay, timeout)
    try:
        conn.request("GET", "/v1/health", headers=signed_headers(relay, "", b""))
        resp = conn.getresponse()
        if resp.status != 200:
            raise relay_error(relay, resp)
        return json.loads(resp.read(4096))
    finally:
        conn.close()


def probe_egress(relay: RelayEndpoint, url: str, timeout: float = 20) -> int:
    """HTTP status Amazon returns to the relay; any answer proves the route works."""
    try:
        with opener_for(relay).open(request.Request(url, method="GET"), timeout=timeout) as resp:
            return resp.getcode()
    except error.HTTPError as exc:
        exc.close()
        return exc.code
